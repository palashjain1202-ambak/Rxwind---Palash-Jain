export type TKey = keyof Dict;

export function tr(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

